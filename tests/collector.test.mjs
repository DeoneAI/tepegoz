import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,readFile,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
const token='test-only-collector-key';
test('collector authenticates, stores, freezes and replays protocol messages through its HTTP handler',async t=>{
  const data=await mkdtemp(path.join(tmpdir(),'sensorlink-test-'));
  process.env.SENSORLINK_TEST='1';process.env.DATA_DIR=data;process.env.COLLECTOR_TOKEN=token;process.env.ALLOWED_ORIGINS='https://frontend.test';
  const {server}=await import('../pc/server.mjs');
  t.after(async()=>{server.close();await rm(data,{recursive:true,force:true});});
  // Exercise the real HTTP listener with streams; loopback sockets are restricted in some sandboxes.
  const req=async(route,key=token,method='GET',value,headers={})=>{
    const bytes=value===undefined?Buffer.alloc(0):Buffer.isBuffer(value)?value:Buffer.from(JSON.stringify(value));
    const input=Readable.from(bytes.length?[bytes]:[]);input.url=route;input.method=method;input.headers={authorization:`Bearer ${key}`,...headers};
    const out={headers:{},status:200,bytes:Buffer.alloc(0),headersSent:false,
      setHeader(k,v){this.headers[k]=v;},writeHead(code,values){this.status=code;Object.assign(this.headers,values);this.headersSent=true;},
      end(b){this.bytes=Buffer.from(b||'');},destroy(){throw new Error('Response destroyed');}};
    await server.listeners('request')[0](input,out);return{status:out.status,headers:out.headers,json:()=>JSON.parse(out.bytes.toString()),bytes:out.bytes};
  };
  assert.equal((await req('/api/sessions','bad')).status,401);
  assert.equal((await req('/api/usb','bad')).status,401);
  assert.equal((await req('/api/usb')).status,403,'USB cannot be controlled through a tunnel or nonlocal request');
  assert.equal((await req('/api/sessions',token,'GET',undefined,{origin:'https://untrusted.test'})).status,403);
  const preflight=await req('/api/sessions/test/frame',token,'OPTIONS',undefined,{origin:'https://frontend.test'});
  assert.equal(preflight.status,204);
  assert.equal(preflight.headers['Access-Control-Max-Age'],'600');
  assert.match(preflight.headers['Access-Control-Allow-Headers'],/X-Frame-Meta/);
  const created=await req('/api/sessions',token,'POST',{name:'Integration test'});assert.equal(created.status,201);const s=created.json();const route=`/api/sessions/${s.id}`;
  assert.equal((await req(route+'/live-image')).status,204,'no frame yet');
  assert.equal((await req(route+'/live-image','bad')).status,401);
  assert.notEqual((await req(route+'/live-image',s.phone_key)).status,200,'phone cannot read live images');
  assert.equal((await req('/api/sessions',s.phone_key)).status,401,'phone cannot list private sessions');
  assert.equal((await req(route+'/sync',s.phone_key,'POST',{t0:100})).status,200);
  assert.equal((await req(route+'/clock',s.phone_key,'POST',{offset_ms:10,rtt_ms:4,phone_ms:100})).status,200);
  const common={session_id:s.id,frame_axes:'phone_portrait_x_right_y_up_z_out',quality:'browser_accuracy_unavailable'};
  const samples=[{...common,sensor_type:'accelerometer',timestamp_ns:'100000000',sequence_id:0,values:{x:0,y:9.81,z:0},units:'m_s2'},{...common,sensor_type:'gyroscope',timestamp_ns:'101000000',sequence_id:0,values:{x:0,y:0,z:.1},units:'rad_s'}];
  assert.equal((await req(route+'/samples',s.phone_key,'POST',{samples})).status,200);
  assert.equal((await req(route+'/samples',s.phone_key,'POST',{samples})).json().accepted,0,'idempotentent retry');
  const gyroView=(await req(route+'?sensor=gyroscope')).json();
  assert.deepEqual(gyroView.telemetry.map(x=>x.sensor_type),['gyroscope']);
  assert.equal(gyroView.metrics.samples,2,'filtering the chart preserves all stored sensor counts');
  const jpeg=Buffer.from([0xff,0xd8,0xff,0xd9]);const meta={frame_index:0,timestamp_ns:'100000000',timestamp_source:'callback_estimate',media_time_s:0,width:640,height:360};
  assert.equal((await req(route+'/frame?meta='+encodeURIComponent(JSON.stringify(meta)),s.phone_key,'POST',jpeg)).status,200);
  const replay=(await req(route+'/replay')).json();assert.equal(replay.frames.length,1);assert.equal(replay.samples.length,2);assert.equal(replay.frames[0].timestamp_ns,meta.timestamp_ns);
  assert.deepEqual((await req(route+'/image?index=0')).bytes,jpeg);
  const live=await req(route+'/live-image');
  assert.deepEqual(live.bytes,jpeg);
  assert.equal(JSON.parse(live.headers['X-Frame-Meta']).frame_index,0);
  assert.equal((await req(route+'/live-image',token,'GET',undefined,{'x-after-frame':'0'})).status,204,'unchanged images are not transferred again');
  const nextMeta={...meta,frame_index:1};
  assert.equal((await req(route+'/frame',s.phone_key,'POST',jpeg,{'x-frame-meta':JSON.stringify(nextMeta)})).status,200);
  const nextLive=await req(route+'/live-image',token,'GET',undefined,{'x-after-frame':'0'});
  assert.equal(JSON.parse(nextLive.headers['X-Frame-Meta']).frame_index,1,'live endpoint selects the newest saved frame');
  const csv=await readFile(path.join(data,s.id,'imu.csv'),'utf8');assert.match(csv,/gyroscope,101000000,0,0,0,0.1,rad_s/);
  assert.equal((await req(route+'/samples',s.phone_key,'POST',{samples:[{...samples[0],session_id:'000000000000000000000000'}]})).status,400);
  const more=[{...samples[0],timestamp_ns:'200000000',sequence_id:1},{...samples[1],timestamp_ns:'201000000',sequence_id:3},{...common,sensor_type:'gnss',frame_axes:'wgs84_geodetic',quality:'browser_geolocation_accuracy',timestamp_ns:'205000000',sequence_id:0,values:{latitude:40.4,longitude:49.8,altitude:null,speed:null,heading:null},accuracy_m:12,units:'deg_m_mps'}];
  assert.equal((await req(route+'/samples',s.phone_key,'POST',{samples:more,dropped_samples:2})).status,200);
  const metrics=(await req(route)).json().metrics;
  assert.equal(metrics.per_sensor_hz.accelerometer,10);assert.equal(metrics.per_sensor_hz.gyroscope,10);
  assert.equal(metrics.per_sensor_hz.gnss,null);assert.equal(metrics.sequence_gaps_by_stream.gyroscope,2);assert.equal(metrics.phone_dropped_samples,2);
  assert.match(await readFile(path.join(data,s.id,'gnss.csv'),'utf8'),/40.4,49.8,,,,12,/);
  assert.equal((await req(route+'/export?file=..%2F..%2Fsecret')).status,400);
  assert.equal((await req('/api/sessions/..%2F..%2Fsecret')).status,400);
  assert.equal((await req(route+'/stop',token,'POST',{})).json().recording,false);
  assert.equal((await req(route+'/samples',s.phone_key,'POST',{samples})).status,409);
  const manifest=JSON.parse(await readFile(path.join(data,s.id,'manifest.json'),'utf8'));assert.equal(manifest.status,'completed');assert.equal(manifest.metrics.frames,2);assert.equal(manifest.metrics.samples,5);
});
